#!/usr/bin/env python3
"""
E9 shared substrate: a graph-structured AUTOREGRESSIVE per-block proposal
q_phi(W | O) = prod_j q_{phi, pi(j)}( W_{pi(j)} | W_{pi(<j)}, O ),  pi = W3 -> W2 -> W1.

Each block W_j = (raw_theta_j, c_j, U_j) is generated by its own conditional
normalizing flow, conditioned on the ALREADY-generated blocks (its separator in
the faithful inverse graph -- a chain b3-b2-b1) plus a routed observation
embedding (b3<-y, b2<-[z2,y], b1<-z1). Because the flow is autoregressive over
blocks, the exact density factorizes as log q = sum_j log q_j, so it is cheap to
evaluate -- which is what the strict IS/SMC weights and (later) GFlowNet need.

This module is deliberately objective-AGNOSTIC: the SAME SeqProposal is trained
three ways in E9 (reverse-KL VI here; VarGrad-TB GFlowNet and learned-proposal
tempered SMC to follow). Fairness rule: identical architecture, only the training
objective changes.

This file currently ships the shared proposal + the VI (reverse-KL) line and a
self-consistency / collapse smoke test on the E8 bimodal testbed.
"""

from __future__ import annotations

import argparse
import json
import math
import time
from pathlib import Path

import numpy as np
import torch

import gen_model as gm
